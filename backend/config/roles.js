function getPermissionsForRole(role) {
  return ROLE_PERMISSIONS[role] || [];
}

function roleHasPermission(role, permission) {
  if (role === ROLES.OWNER) return true;
  return (ROLE_PERMISSIONS[role] || []).includes(permission);
}

